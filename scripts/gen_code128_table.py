def to_bits(widths: list[int]) -> str:
    out = []
    for i, w in enumerate(widths):
        out.append(("1" if i % 2 == 0 else "0") * w)
    return "".join(out)


def main() -> None:
    patterns = re.findall(r"\{([^}]*)\}", DATA)
    assert len(patterns) == 107, len(patterns)
    for idx, ws in enumerate(patterns):
        bits = to_bits([int(x) for x in ws.split(",")])
        expected = 13 if idx == 106 else 11
        assert len(bits) == expected, (idx, len(bits))
        print(f'  "{bits}", // {idx}')


if __name__ == "__main__":
    main()
